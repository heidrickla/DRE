#!/usr/bin/env python3
"""Generate a large grid-navigation pack and experiment.

The shipped `navigation` pack is a 5-by-5 grid that expands 13 states. That
is enough to demonstrate the planner and nowhere near enough to test it: at
13 states the total frontier ordering is not load-bearing, because there
are barely any ties to break. A `BinaryHeap` resolving equal-cost entries
by heap layout would pass every existing experiment.

This writes a grid big enough for that to matter. Obstacles are placed as
regular pillars rather than as a maze, deliberately: a maze has one route
and therefore nothing to tie-break, while an open field of pillars produces
*thousands* of equally optimal routes, which is exactly the case where an
under-specified ordering shows.

Generated packs are legitimate input -- the pack is hashed, so whatever
this writes is covered by the `ModelHash` like any hand-written pack. What
would not be legitimate is computing a *decision* here; see tools/README.md.

Usage:
    python3 tools/generate-grid-pack.py --size 40 --out model-packs/grid-40
"""

import argparse
import os


def pillars(size, spacing):
    """Obstacle cells: a regular lattice with the borders left clear.

    Regular rather than random, so the pack is a deterministic function of
    its arguments and can be regenerated byte-identically. A pack whose
    contents depended on an RNG would have a `ModelHash` that changed every
    time it was written, which is the one thing a model must not do.
    """
    cells = []
    for x in range(spacing, size - 1, spacing):
        for y in range(spacing, size - 1, spacing):
            cells.append((x, y))
    return cells


def cell_condition(x, y, indent):
    pad = " " * indent
    return (
        f"{pad}- all:\n"
        f"{pad}    - subject: agent.x\n"
        f"{pad}      operator: EQ\n"
        f"{pad}      operand: {x}\n"
        f"{pad}    - subject: agent.y\n"
        f"{pad}      operator: EQ\n"
        f"{pad}      operand: {y}\n"
    )


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size", type=int, default=40, help="grid edge length")
    parser.add_argument("--spacing", type=int, default=4, help="obstacle lattice spacing")
    parser.add_argument("--out", required=True, help="pack directory to write")
    parser.add_argument("--experiment", help="experiment file to write")
    parser.add_argument(
        "--goal",
        help="goal cell as X,Y. Defaults to the far corner, where every cell "
        "lies on some shortest path and A* has nothing to discriminate on.",
    )
    parser.add_argument(
        "--strategy",
        choices=("breadth_first", "dijkstra", "astar"),
        help="search strategy the generated experiment declares. Omitted "
        "means the engine default, which is dijkstra.",
    )
    args = parser.parse_args()

    size = args.size
    last = size - 1
    obstacles = pillars(size, args.spacing)

    # The pack identifier follows the directory it is written to, so a
    # second pack of the same size but a different goal does not collide
    # with the first. `--out model-packs/grid-40` still yields `grid-40`,
    # which is what keeps the shipped pack regenerating byte-identically.
    out = args.out.replace(os.sep, "/").rstrip("/")
    pack_id = out.rsplit("/", 1)[-1]

    if args.goal:
        goal_x, goal_y = (int(part) for part in args.goal.split(","))
    else:
        goal_x, goal_y = last, last

    for name, value in (("x", goal_x), ("y", goal_y)):
        if not 0 <= value <= last:
            parser.error(f"goal {name}={value} is off a {size}-by-{size} grid")
    if (goal_x, goal_y) in obstacles:
        parser.error(f"goal {goal_x},{goal_y} is an obstacle cell")

    corner = (goal_x, goal_y) == (last, last)

    os.makedirs(args.out, exist_ok=True)

    write(
        os.path.join(args.out, "model.yaml"),
        f"""# GENERATED by tools/generate-grid-pack.py -- do not edit by hand.
#
# A {size}-by-{size} grid with a lattice of obstacles every {args.spacing} cells.
#
# The point of the size is the tie-breaking. An open grid this large
# produces thousands of equally optimal routes, so the planner's frontier
# ordering is doing real work on every expansion rather than almost never.
# The 5-by-5 pack expands 13 states and could not distinguish a total
# ordering from a lucky one.

model:
  id: {pack_id}
  version: 0.1.0
  requires_engine: 0.1.0
  description: >-
    Generated {size}-by-{size} navigation grid with {len(obstacles)} obstacles.
    Exercises the planner at a scale where equal-cost paths are the norm.
""",
    )

    write(
        os.path.join(args.out, "ontology.yaml"),
        f"""# GENERATED by tools/generate-grid-pack.py -- do not edit by hand.

entities:
  agent:
    properties:
      x:
        type: integer
        min: 0
        max: {last}
      y:
        type: integer
        min: 0
        max: {last}
""",
    )

    write(
        os.path.join(args.out, "causal.yaml"),
        f"""# GENERATED by tools/generate-grid-pack.py -- do not edit by hand.
#
# Unit-cost moves in four directions, guarded so the agent stays on the
# grid. Preconditions keep it in bounds; obstacles are constraints, so a
# blocked move is recorded as a rejected candidate in the proof rather than
# silently unavailable.

actions:
  - id: MOVE_EAST
    description: Increase x by one.
    preconditions:
      - subject: agent.x
        operator: LTE
        operand: {last - 1}
    effects:
      agent.x:
        add: 1
    cost: 1
    reversible: true

  - id: MOVE_NORTH
    description: Increase y by one.
    preconditions:
      - subject: agent.y
        operator: LTE
        operand: {last - 1}
    effects:
      agent.y:
        add: 1
    cost: 1
    reversible: true

  - id: MOVE_SOUTH
    description: Decrease y by one.
    preconditions:
      - subject: agent.y
        operator: GTE
        operand: 1
    effects:
      agent.y:
        add: -1
    cost: 1
    reversible: true

  - id: MOVE_WEST
    description: Decrease x by one.
    preconditions:
      - subject: agent.x
        operator: GTE
        operand: 1
    effects:
      agent.x:
        add: -1
    cost: 1
    reversible: true
""",
    )

    walls = "".join(cell_condition(x, y, 12) for x, y in obstacles)
    write(
        os.path.join(args.out, "constraints.yaml"),
        f"""# GENERATED by tools/generate-grid-pack.py -- do not edit by hand.
#
# {len(obstacles)} obstacle cells, one nested clause each.
#
# The size of this file is itself a finding. The constraint language has no
# way to say "these cells are walls" compactly, so a grid of any size
# produces a constraint proportional to the number of obstacles. That is
# fine for a generated pack and would be unbearable by hand, which is the
# honest reason this generator exists.

constraints:
  - id: C001
    description: The agent must not occupy an obstacle cell.
    hard: true
    conditions:
      - not:
          any:
{walls}""",
    )

    if corner:
        goal_note = """# The far corner. Every cell then lies on some shortest path, so g + h is
# nearly constant and A* has little to discriminate on -- which is the
# known degeneracy of Manhattan distance on an open grid, and worth
# measuring at this size rather than assuming.
#
# Measured, and it is exact rather than approximate: A* and Dijkstra expand
# the same 1518 states here and return the same 78-step plan. The heuristic
# is not weak on this goal, it is inert."""
        goal_description = "Stand on the far corner."
    else:
        goal_note = f"""# A goal away from the corner, which is the only placement where the
# heuristic can do anything. Cells beyond ({goal_x}, {goal_y}) lie on no shortest path
# from the origin, so g + h ranks them worse and A* declines to expand
# them -- where a far-corner goal leaves nothing outside the useful region
# to decline.
#
# This is the measurement the far-corner pack cannot make. Both searches
# return the same optimal plan; A* reaches it having expanded roughly half
# as many states."""
        goal_description = f"Stand on ({goal_x}, {goal_y})."

    write(
        os.path.join(args.out, "goals.yaml"),
        f"""# GENERATED by tools/generate-grid-pack.py -- do not edit by hand.
#
{goal_note}

goals:
  - id: REACH_GOAL
    description: {goal_description}
    conditions:
      - subject: agent.x
        operator: EQ
        operand: {goal_x}
      - subject: agent.y
        operator: EQ
        operand: {goal_y}
""",
    )

    if args.experiment:
        # Manhattan distance from the origin, plus whatever detour the
        # obstacles force. Declared as a bound rather than an exact figure:
        # the generator must not compute the answer.
        plan_len = goal_x + goal_y
        depth_needed = plan_len + 8

        if corner:
            purpose = """# The scale experiment. Everything else in experiments/ is small enough to
# check by hand; this one is not, and that is the point."""
            reach = "Exercises the planner where equal-cost paths are the norm rather than\n    the exception, which is the only condition under which the frontier's\n    total ordering is load-bearing."
        else:
            purpose = """# The scale experiment with a goal the heuristic can work on. The
# far-corner pack measures the planner; this one measures the guidance,
# which is inert at the corner and cannot be assessed there."""
            reach = "Exercises the heuristic where it has something to prune: cells beyond\n    the goal lie on no shortest path from the origin, so g + h ranks them\n    worse and A* never expands them."

        strategy_line = f"\n  strategy: {args.strategy}\n" if args.strategy else ""

        write(
            args.experiment,
            f"""# GENERATED by tools/generate-grid-pack.py -- do not edit by hand.
#
{purpose}
#
# It declares raised ceilings, which puts it on a different EngineHash from
# the other experiments. That is correct rather than unfortunate: a run
# under different limits can legitimately reach a different answer, having
# explored states the default engine would have refused.

experiment:
  id: {pack_id}-001
  description: >-
    Navigation across a {size}-by-{size} grid with {len(obstacles)} obstacles.
    {reach}
  pack: {out}
{strategy_line}
  # The default depth of 20 does not reach a goal {plan_len} steps away.
  # Raising it is an admission that this needs a different engine, not a
  # way to make the problem fit.
  limits:
    max_depth: {depth_needed}

  given:
    entities:
      - id: agent
        type: agent
        properties:
          - name: x
            value: 0
            status: KNOWN
          - name: y
            value: 0
            status: KNOWN

  expect:
    # The planner plans; it does not execute. So the agent is still at the
    # origin when the run ends, and asserting otherwise would be asserting
    # that the engine does something it deliberately does not.
    #
    # What is worth asserting is optimality. {goal_x} east and {goal_y} north is the
    # Manhattan distance, and the obstacle lattice leaves a monotone route
    # open, so a plan of exactly {plan_len} steps is the shortest one that
    # exists. Which of the thousands of equally short routes comes back is
    # the frontier ordering's business, and is pinned by the replay record
    # rather than by this file.
    plan_length: {plan_len}
""",
        )

    print(f"wrote {args.out}: {size}x{size}, {len(obstacles)} obstacles")
    if args.experiment:
        print(f"wrote {args.experiment}")


if __name__ == "__main__":
    main()
